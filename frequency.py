import sys

input = sys.argv[1].upper


def find_letter_frequency(input_string):
    letter_count = {
        "A": 0,
        "B": 0,
        "C": 0,
        "D": 0,
        "E": 0,
        "F": 0,
        "G": 0,
        "H": 0,
        "I": 0,
        "J": 0,
        "K": 0,
        "L": 0,
        "M": 0,
        "N": 0,
        "O": 0,
        "P": 0,
        "Q": 0,
        "R": 0,
        "S": 0,
        "T": 0,
        "U": 0,
        "V": 0,
        "W": 0,
        "X": 0,
        "Y": 0,
        "Z": 0,
    }

    for char in input_string.upper():
        if char in letter_count:
            letter_count[char] += 1

    print(letter_count)


find_letter_frequency(sys.argv[1])
